//! Astro Block's own pixel font: a condensed, square-cornered geometric face (glyphs 4 pixels
//! wide, capitals 6 tall, a tall lowercase with short descenders). ASCII 32..=126.
//!
//! Glyphs sit in 5x9 cells (one column and row of spacing) of a 16x6 atlas. Character 127 is
//! a solid cell, used for filled rectangles.

/// Atlas cell size in pixels.
pub const CELL: (u32, u32) = (5, 9);
const COLUMNS: u32 = 16;
const ROWS: u32 = 6;
pub const ATLAS_SIZE: (u32, u32) = (CELL.0 * COLUMNS, CELL.1 * ROWS);
/// The solid block "glyph".
pub const SOLID: char = '\u{7f}';

