/// RGBA8 atlas: white, with the glyph in alpha.
pub fn atlas() -> Vec<u8> {
    let (w, h) = ATLAS_SIZE;
    let mut pixels = vec![0u8; (w * h * 4) as usize];
    for code in 32u32..=127 {
        let (cx, cy) = (
            ((code - 32) % COLUMNS) * CELL.0,
            ((code - 32) / COLUMNS) * CELL.1,
        );
        for y in 0..CELL.1 {
            for x in 0..CELL.0 {
                let on = if code == 127 {
                    true
                } else {
                    let rows = GLYPHS[(code - 32) as usize];
                    y < 8 && x < 4 && rows[y as usize].as_bytes()[x as usize] == b'#'
                };
                let i = (((cy + y) * w + cx + x) * 4) as usize;
                pixels[i..i + 4].copy_from_slice(&[255, 255, 255, if on { 255 } else { 0 }]);
            }
        }
    }
    pixels
}

/// Atlas uv rectangle (min, max) of a character's cell; unknown characters show as '?'.
pub fn glyph_uv(c: char) -> ([f32; 2], [f32; 2]) {
    let code = c as u32;
    let code = if (32..=127).contains(&code) {
        code
    } else {
        '?' as u32
    };
    let (cx, cy) = (
        ((code - 32) % COLUMNS) * CELL.0,
        ((code - 32) / COLUMNS) * CELL.1,
    );
    let (w, h) = (ATLAS_SIZE.0 as f32, ATLAS_SIZE.1 as f32);
    (
        [cx as f32 / w, cy as f32 / h],
        [(cx + CELL.0) as f32 / w, (cy + CELL.1) as f32 / h],
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyphs_are_well_formed() {
        for (i, rows) in GLYPHS.iter().enumerate() {
            for row in rows {
                assert_eq!(row.len(), 4, "glyph {} row {row:?}", (i as u8 + 32) as char);
                assert!(row.bytes().all(|b| b == b'#' || b == b'.'));
            }
        }
        // Every printable character except space has ink.
        for (i, rows) in GLYPHS.iter().enumerate().skip(1) {
            assert!(
                rows.iter().any(|r| r.contains('#')),
                "{}",
                (i as u8 + 32) as char
            );
        }
    }
}
